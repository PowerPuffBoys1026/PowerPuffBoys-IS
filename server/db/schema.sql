-- ClassMate PostgreSQL schema
--
-- The API applies this file automatically on startup and `npm run db:init`
-- applies it after creating the database if needed.
--
-- Manual use:
--   createdb -h localhost -U postgres classmate
--   psql -h localhost -U postgres -d classmate -f db/schema.sql
--
-- If you use a custom schema instead of "public", create it and set the search
-- path first, then run this file:
--   CREATE SCHEMA IF NOT EXISTS classmate;
--   SET search_path TO classmate;

CREATE TABLE IF NOT EXISTS users (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email         TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  full_name     TEXT NOT NULL,
  student_no    TEXT,
  course        TEXT,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS subjects (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  code       TEXT NOT NULL,
  title      TEXT NOT NULL,
  instructor TEXT,
  units      INTEGER NOT NULL DEFAULT 0 CHECK (units >= 0),
  color      TEXT NOT NULL DEFAULT '#4F46E5',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS schedule_slots (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_id  INTEGER NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
  day_of_week SMALLINT NOT NULL CHECK (day_of_week BETWEEN 0 AND 6),
  start_time  TIME NOT NULL,
  end_time    TIME NOT NULL,
  room        TEXT,
  modality    TEXT
);

CREATE TABLE IF NOT EXISTS attendance_records (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_id INTEGER NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
  slot_id    INTEGER REFERENCES schedule_slots(id) ON DELETE SET NULL,
  date       DATE NOT NULL,
  status     TEXT NOT NULL CHECK (status IN ('present', 'absent', 'late', 'cancelled')),
  note       TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS school_works (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  subject_id INTEGER REFERENCES subjects(id) ON DELETE SET NULL,
  title      TEXT NOT NULL,
  type       TEXT NOT NULL DEFAULT 'assignment'
             CHECK (type IN ('assignment', 'quiz', 'exam', 'project')),
  due_at     TIMESTAMPTZ,
  priority   TEXT NOT NULL DEFAULT 'medium'
             CHECK (priority IN ('low', 'medium', 'high')),
  status     TEXT NOT NULL DEFAULT 'todo'
             CHECK (status IN ('todo', 'doing', 'done')),
  notes      TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS notes (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title      TEXT NOT NULL DEFAULT 'Untitled',
  content    TEXT NOT NULL DEFAULT '',
  is_pinned  BOOLEAN NOT NULL DEFAULT false,
  color      TEXT DEFAULT '#1C223D',
  tags       TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_subjects_user      ON subjects(user_id);
CREATE INDEX IF NOT EXISTS idx_slots_subject      ON schedule_slots(subject_id);
CREATE INDEX IF NOT EXISTS idx_attendance_subject ON attendance_records(subject_id);
CREATE INDEX IF NOT EXISTS idx_works_user         ON school_works(user_id);
CREATE INDEX IF NOT EXISTS idx_works_due          ON school_works(due_at);
CREATE INDEX IF NOT EXISTS idx_notes_user         ON notes(user_id);
CREATE INDEX IF NOT EXISTS idx_notes_updated      ON notes(updated_at);
